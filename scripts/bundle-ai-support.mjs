/**
 * Bundle docs/support sources into root AI-SUPPORT.md.
 * Usage:
 *   node scripts/bundle-ai-support.mjs           # write AI-SUPPORT.md
 *   node scripts/bundle-ai-support.mjs --check   # compare, do not write
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

const SOURCES = [
  'docs/ai-support-front.md',
  'docs/product.md',
  'docs/getting-started.md',
  'docs/user-guide.md',
  'docs/configuration.md',
  'docs/reference.md',
  'docs/troubleshooting.md',
  'docs/app-architecture.md',
  'docs/development.md',
  'docs/FAQ.md',
  'docs/roadmap.md'
]

function bundle() {
  const parts = [
    '<!-- Generated by scripts/bundle-ai-support.mjs. Do not edit by hand. -->',
    ''
  ]
  for (const rel of SOURCES) {
    const body = readFileSync(join(root, rel), 'utf8').replace(/\r\n/g, '\n').trimEnd()
    parts.push(`<!-- source: ${rel} -->`)
    parts.push('')
    parts.push(body)
    parts.push('')
  }
  return parts.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n'
}

const check = process.argv.includes('--check')
const next = bundle()
const outPath = join(root, 'AI-SUPPORT.md')

if (check) {
  let current = ''
  try {
    current = readFileSync(outPath, 'utf8').replace(/\r\n/g, '\n')
  } catch {
    console.error('AI-SUPPORT.md is missing. Run: npm run docs:bundle')
    process.exit(1)
  }
  if (current !== next) {
    console.error('AI-SUPPORT.md is stale. Run: npm run docs:bundle')
    process.exit(1)
  }
  const readme = readFileSync(join(root, 'README.md'), 'utf8')
  if (!readme.includes('](AI-SUPPORT.md)') && !readme.includes('](./AI-SUPPORT.md)')) {
    console.error('README.md is missing a Markdown link to AI-SUPPORT.md')
    process.exit(1)
  }
  for (const rel of SOURCES) {
    if (!next.includes(`<!-- source: ${rel} -->`)) {
      console.error(`Bundle missing source marker for ${rel}`)
      process.exit(1)
    }
  }
  console.log('AI-SUPPORT.md matches source documents.')
} else {
  writeFileSync(outPath, next)
  console.log(`Wrote ${outPath} (${next.split('\n').length} lines)`)
}
